"""
Diabetes Risk Checkup - Streamlit App
=======================================
The "Proposed Solution: The Visualized Checkup Application" from the brief:
  - User-friendly input form (Streamlit front-end)
  - Personalized visualization: risk probability gauge + SHAP feature contribution plot
  - Actionable report: downloadable PDF summary with risk explanation

Run with:  streamlit run app.py
(Run train_models.py first so saved_models/ and reports/ are populated.)
"""

import io
import os
import joblib
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import shap
import streamlit as st
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from reportlab.lib.units import cm
from sklearn.metrics import confusion_matrix

ROOT = os.path.dirname(os.path.abspath(__file__))
MODEL_DIR = os.path.join(ROOT, "saved_models")
REPORT_DIR = os.path.join(ROOT, "reports")
FEATURE_COLS = [
    "Pregnancies", "Glucose", "BloodPressure", "SkinThickness",
    "Insulin", "BMI", "DiabetesPedigreeFunction", "Age"
]

st.set_page_config(page_title="Diabetes Risk Checkup", page_icon="🩺", layout="wide")


@st.cache_resource
def load_artifacts():
    if not os.path.exists(f"{MODEL_DIR}/best_model.pkl"):
        return None
    model = joblib.load(f"{MODEL_DIR}/best_model.pkl")
    rf_model = joblib.load(f"{MODEL_DIR}/rf_model_for_shap.pkl")
    scaler = joblib.load(f"{MODEL_DIR}/scaler.pkl")
    imputer = joblib.load(f"{MODEL_DIR}/imputer.pkl")
    with open(f"{MODEL_DIR}/best_model_name.txt") as f:
        best_name = f.read().strip()
    return model, rf_model, imputer, scaler, best_name


def risk_gauge(probability):
    """Draw a simple speedometer-style risk gauge (matches the 'risk probability gauges' brief item)."""
    fig, ax = plt.subplots(figsize=(4, 2.4), subplot_kw={"projection": "polar"})

    # background bands: green / yellow / red
    bands = [(0, 0.33, "#2ecc71"), (0.33, 0.66, "#f1c40f"), (0.66, 1.0, "#e74c3c")]
    for start, end, color in bands:
        ax.barh(1, (end - start) * np.pi, left=start * np.pi, height=1, color=color, alpha=0.85)

    # needle
    needle_angle = probability * np.pi
    ax.plot([needle_angle, needle_angle], [0, 1], color="black", linewidth=3)
    ax.scatter([needle_angle], [0], color="black", s=60, zorder=5)

    ax.set_theta_zero_location("W")
    ax.set_theta_direction(-1)
    ax.set_thetamin(0)
    ax.set_thetamax(180)
    ax.set_yticklabels([])
    ax.set_xticklabels([])
    ax.set_ylim(0, 1)
    ax.spines["polar"].set_visible(False)
    ax.grid(False)
    plt.title(f"Model score: {probability:.1%}", fontsize=13, pad=10)
    plt.tight_layout()
    return fig


def shap_waterfall_for_patient(rf_model, imputer, scaler, patient_df):
    explainer = shap.TreeExplainer(rf_model)
    patient_scaled = scaler.transform(imputer.transform(patient_df))
    patient_scaled_df = pd.DataFrame(patient_scaled, columns=FEATURE_COLS)
    shap_values = explainer.shap_values(patient_scaled_df)

    if isinstance(shap_values, list):
        sv = shap_values[1][0]
        base_value = explainer.expected_value[1]
    elif shap_values.ndim == 3:
        sv = shap_values[0, :, 1]
        base_value = explainer.expected_value[1]
    else:
        sv = shap_values[0]
        base_value = explainer.expected_value

    explanation = shap.Explanation(
        values=sv,
        base_values=base_value,
        data=patient_df.iloc[0].values,
        feature_names=FEATURE_COLS,
    )
    fig = plt.figure(figsize=(7, 4))
    shap.plots.waterfall(explanation, show=False, max_display=8)
    plt.tight_layout()
    return fig


def generate_pdf_report(patient_data, probability, risk_label, top_factors):
    """Actionable report: automated PDF summary (brief item 3 of the Proposed Solution)."""
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    width, height = A4

    c.setFont("Helvetica-Bold", 18)
    c.drawString(2 * cm, height - 2 * cm, "Diabetes Risk Checkup Report")

    c.setFont("Helvetica", 10)
    c.drawString(2 * cm, height - 2.8 * cm, "Generated by the ML Diabetes Prediction demo project (for academic use only).")

    c.setFont("Helvetica-Bold", 13)
    c.drawString(2 * cm, height - 4 * cm, f"Model score: {probability:.1%}  |  {risk_label}")

    c.setFont("Helvetica-Bold", 12)
    c.drawString(2 * cm, height - 5.2 * cm, "Patient Inputs")
    c.setFont("Helvetica", 10)
    y = height - 5.9 * cm
    for k, v in patient_data.items():
        c.drawString(2.3 * cm, y, f"- {k}: {v}")
        y -= 0.55 * cm

    c.setFont("Helvetica-Bold", 12)
    y -= 0.4 * cm
    c.drawString(2 * cm, y, "Top Contributing Factors (SHAP)")
    y -= 0.7 * cm
    c.setFont("Helvetica", 10)
    for feat, val in top_factors:
        direction = "increases" if val > 0 else "decreases"
        c.drawString(2.3 * cm, y, f"- {feat}: {direction} risk (impact {val:+.3f})")
        y -= 0.55 * cm

    y -= 0.6 * cm
    c.setFont("Helvetica-Bold", 12)
    c.drawString(2 * cm, y, "Recommended Next Steps")
    y -= 0.7 * cm
    c.setFont("Helvetica", 10)
    steps = [
        "Discuss this result with a qualified healthcare provider.",
        "Consider a confirmatory fasting glucose / HbA1c test.",
        "Review diet, physical activity, and weight management with a clinician.",
        "Re-check periodically, especially if key risk factors change.",
    ]
    for s in steps:
        c.drawString(2.3 * cm, y, f"- {s}")
        y -= 0.55 * cm

    c.setFont("Helvetica-Oblique", 8)
    c.drawString(2 * cm, 1.5 * cm,
                 "Disclaimer: This is a student ML project for educational purposes only, "
                 "not a medical diagnostic device.")
    c.showPage()
    c.save()
    buf.seek(0)
    return buf


def main():
    st.title("🩺 Diabetes Risk Studio")
    st.markdown("### An explainable machine learning screening demo")
    st.caption(
        "Explore how clinical measurements move a model score, compare model performance, "
        "and inspect a local SHAP explanation. Built for an ML classroom demonstration."
    )

    artifacts = load_artifacts()
    if artifacts is None:
        st.error("No trained model found. Run `python train_models.py` first to generate saved_models/.")
        return
    model, rf_model, imputer, scaler, best_name = artifacts

    st.sidebar.header("Explore a sample profile")
    st.sidebar.caption("Adjust measurements, then run the model.")
    pregnancies = st.sidebar.number_input("Pregnancies", 0, 20, 2)
    glucose = st.sidebar.slider("Glucose (mg/dL)", 40, 250, 120)
    blood_pressure = st.sidebar.slider("Blood Pressure (mm Hg)", 30, 140, 70)
    skin_thickness = st.sidebar.slider("Skin Thickness (mm)", 0, 100, 20)
    insulin = st.sidebar.slider("Insulin (mu U/mL)", 0, 900, 80)
    bmi = st.sidebar.slider("BMI", 10.0, 70.0, 28.0, step=0.1)
    dpf = st.sidebar.slider("Diabetes Pedigree Function", 0.0, 2.5, 0.4, step=0.01)
    age = st.sidebar.slider("Age", 15, 100, 33)

    st.sidebar.markdown(f"**Selected model:** {best_name}")
    threshold = st.sidebar.slider("Classification threshold", 0.05, 0.95, 0.50, 0.05,
                                  help="Scores at or above this value are classified positive. This is an educational control, not a clinical cutoff.")
    predict_btn = st.sidebar.button("Run demo prediction", type="primary")
    if predict_btn:
        st.session_state["show_prediction"] = True

    patient_data = {
        "Pregnancies": pregnancies, "Glucose": glucose, "BloodPressure": blood_pressure,
        "SkinThickness": skin_thickness, "Insulin": insulin, "BMI": bmi,
        "DiabetesPedigreeFunction": dpf, "Age": age,
    }
    patient_df = pd.DataFrame([patient_data])[FEATURE_COLS]

    if st.session_state.get("show_prediction", False):
        probability = model.predict_proba(patient_df)[0, 1]
        predicted_class = int(probability >= threshold)
        risk_label = "Positive at selected threshold" if predicted_class else "Negative at selected threshold"

        col1, col2 = st.columns([1, 1.3])
        with col1:
            st.pyplot(risk_gauge(probability))
            st.metric("Model score", f"{probability:.1%}")
            st.metric("Classification", "Positive" if predicted_class else "Negative",
                      f"Threshold: {threshold:.0%}")
            st.caption("This is a model classification at a user-selected threshold, not a clinical result.")

        with col2:
            st.subheader("Why this prediction? (SHAP explanation)")
            fig = shap_waterfall_for_patient(rf_model, imputer, scaler, patient_df)
            st.pyplot(fig)

        # Compute top factors for the PDF
        explainer = shap.TreeExplainer(rf_model)
        patient_scaled = scaler.transform(imputer.transform(patient_df))
        patient_scaled_df = pd.DataFrame(patient_scaled, columns=FEATURE_COLS)
        shap_values = explainer.shap_values(patient_scaled_df)
        if isinstance(shap_values, list):
            sv = shap_values[1][0]
        elif shap_values.ndim == 3:
            sv = shap_values[0, :, 1]
        else:
            sv = shap_values[0]
        factor_pairs = sorted(zip(FEATURE_COLS, sv), key=lambda x: abs(x[1]), reverse=True)[:5]

        st.divider()
        pdf_buf = generate_pdf_report(patient_data, probability, risk_label, factor_pairs)
        st.download_button(
            "📄 Download PDF Report", data=pdf_buf, file_name="diabetes_risk_report.pdf",
            mime="application/pdf",
        )
        st.info("This tool is an academic project demo and is **not** a medical diagnosis. "
                "Always consult a qualified healthcare professional.")
    else:
        st.info("Set sample values, choose a threshold, then click **Run demo prediction** to explore the model.")

    st.subheader("Threshold explorer")
    st.caption("Change the sidebar threshold and see how classifications shift on the held-out test set. A lower threshold usually finds more positives but can increase false alarms.")
    prediction_path = os.path.join(REPORT_DIR, "test_predictions.csv")
    if os.path.exists(prediction_path):
        heldout = pd.read_csv(prediction_path)
        actual = heldout["actual"].astype(int).to_numpy()
        predicted = (heldout["probability"].to_numpy() >= threshold).astype(int)
        tn, fp, fn, tp = confusion_matrix(actual, predicted, labels=[0, 1]).ravel()
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / (tp + fn) if tp + fn else 0.0
        specificity = tn / (tn + fp) if tn + fp else 0.0
        a, b, c, d = st.columns(4)
        a.metric("True positives", int(tp))
        b.metric("False positives", int(fp))
        c.metric("False negatives", int(fn))
        d.metric("True negatives", int(tn))
        a, b, c = st.columns(3)
        a.metric("Precision", f"{precision:.1%}")
        b.metric("Recall", f"{recall:.1%}")
        c.metric("Specificity", f"{specificity:.1%}")
        st.dataframe(pd.DataFrame([[tn, fp], [fn, tp]],
                                  index=["Actual negative", "Actual positive"],
                                  columns=["Predicted negative", "Predicted positive"]),
                     use_container_width=True)
        st.caption(f"Held-out sample: {len(actual)} records. Threshold controls are for learning and are not medically validated.")
    else:
        st.warning("Held-out prediction file not found. Run `python train_models.py` to generate it.")

    st.subheader("Model comparison")
    st.caption(f"The app uses **{best_name}**, selected by mean training-fold ROC-AUC. Compare that stability estimate with held-out test performance below.")
    metrics_path = os.path.join(REPORT_DIR, "model_comparison.csv")
    if os.path.exists(metrics_path):
        results = pd.read_csv(metrics_path)
        metric_options = {
            "Test ROC-AUC": "roc_auc",
            "Cross-validation ROC-AUC (mean)": "cv_auc_mean",
            "Recall": "recall",
            "Precision": "precision",
            "Balanced accuracy": "balanced_accuracy",
            "F1 score": "f1_score",
            "Specificity": "specificity",
        }
        selected_metric = st.selectbox("Compare models by", list(metric_options))
        metric_col = metric_options[selected_metric]
        chart_data = results.set_index("model")[[metric_col]].sort_values(metric_col, ascending=True)
        st.caption(f"{selected_metric} by model · higher is better")
        st.bar_chart(chart_data)
        with st.expander("See all evaluation metrics"):
            st.dataframe(results.sort_values("cv_auc_mean", ascending=False).style.format(precision=3),
                         use_container_width=True)
        curves_path = os.path.join(REPORT_DIR, "model_curves.png")
        if os.path.exists(curves_path):
            st.image(curves_path, caption="ROC and precision–recall curves · held-out test set", use_container_width=True)
        shap_path = os.path.join(REPORT_DIR, "shap_summary.png")
        if os.path.exists(shap_path):
            with st.expander("Global SHAP feature effects"):
                st.image(shap_path, use_container_width=True)
    else:
        st.info("Run `python train_models.py` to generate model comparison results.")


if __name__ == "__main__":
    main()
